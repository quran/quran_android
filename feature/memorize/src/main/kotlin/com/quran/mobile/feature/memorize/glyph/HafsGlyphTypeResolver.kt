package com.quran.mobile.feature.memorize.glyph

import android.content.Context
import com.quran.data.di.AppScope
import com.quran.mobile.di.qualifier.ApplicationContext
import com.quran.page.common.data.coordinates.GlyphSize
import com.quran.page.common.data.coordinates.GlyphTypeResolver
import dev.zacsweers.metro.ContributesIntoSet
import dev.zacsweers.metro.Inject
import dev.zacsweers.metro.SingleIn

/**
 * Glyph types for any page type of the Hafs text: what the text has in each ayah (its words, and
 * whether it carries a hizb or sajdah marker) comes from the bundled sequence, and the page type's
 * own glyphs tell where its font puts the waqf marks (see [GlyphTypes.derive]).
 */
@SingleIn(AppScope::class)
@ContributesIntoSet(AppScope::class)
class HafsGlyphTypeResolver @Inject constructor(
  @param:ApplicationContext private val context: Context
) : GlyphTypeResolver {

  private val sequences: Map<Int, String> by lazy { load() }

  override fun glyphTypes(sura: Int, ayah: Int, glyphs: List<GlyphSize>): String? =
    sequences[key(sura, ayah)]?.let { GlyphTypes.derive(it, glyphs) }

  /** The text's sequence of glyph types for an ayah, as drawn in the madani mushaf. */
  fun sequence(sura: Int, ayah: Int): String? = sequences[key(sura, ayah)]

  private fun load(): Map<Int, String> {
    val result = HashMap<Int, String>(6_300)
    context.assets.open(ASSET).use { input ->
      input.bufferedReader().useLines { lines ->
        lines.forEach { line ->
          val parts = line.split(' ')
          if (parts.size == 3) {
            result[key(parts[0].toInt(), parts[1].toInt())] = parts[2]
          }
        }
      }
    }
    return result
  }

  private fun key(sura: Int, ayah: Int) = sura * 1000 + ayah

  private companion object {
    // generated by tools/memorize/build_glyph_types.py from the madani ayahinfo databases; stored
    // uncompressed in the source tree (the APK compresses assets itself)
    const val ASSET = "memorize/glyph_types_madani_v1.txt"
  }
}
