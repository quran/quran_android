package com.quran.labs.androidquran.buildutil.qaricatalog

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LIST
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.moshi.Moshi

internal object QariCatalogGenerator {
  const val FILE_NAME = "Qaris"
  private val qariType = ClassName("com.quran.data.model.audio", "Qari")
  private val namePattern = Regex("[a-z][a-z0-9_]*")
  private val adapter = Moshi.Builder()
    .build()
    .adapter(QariCatalog::class.java)
    .failOnUnknown()

  fun generate(json: String, moduleNamespace: String): String {
    val catalog = requireNotNull(adapter.fromJson(json)) {
      "The qari catalog must be a JSON object"
    }
    require(catalog.schemaVersion == 1) { "Unsupported qari catalog schemaVersion; expected 1" }
    require(catalog.qaris.isNotEmpty()) { "qaris must be a non-empty array" }
    val resourceType = ClassName(catalog.resourcePackage ?: moduleNamespace, "R")

    val ids = mutableSetOf<Int>()
    val initializer = CodeBlock.builder().add("listOf(\n").indent()
    catalog.qaris.forEachIndexed { index, value ->
      val context = "qaris[$index]"
      require(value.id >= 0) { "$context.id must be a non-negative integer" }
      require(ids.add(value.id)) { "$context has duplicate qari id ${value.id}" }
      require(namePattern.matches(value.nameResource)) { "$context.nameResource must be a string resource name" }
      require(value.url.endsWith('/')) { "$context.url must end with '/'" }
      require(value.opusUrl == null || value.opusUrl.endsWith('/')) { "$context.opusUrl must end with '/'" }

      initializer.add("%T(\n", qariType).indent()
        .add("id = %L,\n", value.id)
        .add("nameResource = %T.string.%N,\n", resourceType, value.nameResource)
        .add("url = %S,\n", value.url)
        .add("opusUrl = %S,\n", value.opusUrl)
        .add("path = %S,\n", value.path)
        .add("hasGaplessAlternative = %L,\n", value.hasGaplessAlternative)
        .add("db = %S,\n", value.db)
        .unindent().add("),\n")
    }
    initializer.unindent().add(")")

    val listType = LIST.parameterizedBy(qariType)
    return FileSpec.builder(moduleNamespace, FILE_NAME)
      .addFileComment("Generated by quran.qari-catalog. Do not edit.")
      .indent("  ")
      .addProperty(
        PropertySpec.builder("qariList", listType, KModifier.PRIVATE)
          .initializer(initializer.build())
          .build()
      )
      .addFunction(
        FunSpec.builder("qaris")
          .returns(listType)
          .addStatement("return qariList")
          .build()
      )
      .build()
      .toString()
  }
}
